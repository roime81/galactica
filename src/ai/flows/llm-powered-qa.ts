'use server';

/**
 * @fileOverview A flow to enable natural language Q&A for Gold-layer data using a free LLM.
 *
 * - llmPoweredQA - A function that handles the question answering process.
 * - LLMPoweredQAInput - The input type for the llmPoweredQA function.
 * - LLMPoweredQAOutput - The return type for the llmPoweredQA function.
 */

import {ai} from '@/ai/genkit';
import {z} from 'genkit';

const LLMPoweredQAInputSchema = z.object({
  question: z.string().describe('The natural language question about the data.'),
  data: z.string().describe('The data from the Gold layer to answer the question.'),
  useTool: z.boolean().optional().describe('Whether to use the data retrieval tool.'),
});
export type LLMPoweredQAInput = z.infer<typeof LLMPoweredQAInputSchema>;

const LLMPoweredQAOutputSchema = z.object({
  answer: z.string().describe('The answer to the question, generated by the LLM.'),
});
export type LLMPoweredQAOutput = z.infer<typeof LLMPoweredQAOutputSchema>;

export async function llmPoweredQA(input: LLMPoweredQAInput): Promise<LLMPoweredQAOutput> {
  return llmPoweredQAFlow(input);
}

const dataRetrievalTool = ai.defineTool({
  name: 'getData',
  description: 'Retrieves specific data based on the user question from the Gold Layer.',
  inputSchema: z.object({
    query: z.string().describe('The query to use to retrieve the data.')
  }),
  outputSchema: z.string(),
}, async (input) => {
  // In a real application, this would connect to the Firestore
  // or BigQuery and retrieve the data based on the query.
  // For this prototype, we'll just return a placeholder.
  return `Retrieved data: ${input.query}`;
});


const prompt = ai.definePrompt({
  name: 'llmPoweredQAPrompt',
  input: {schema: LLMPoweredQAInputSchema},
  output: {schema: LLMPoweredQAOutputSchema},
  tools: [dataRetrievalTool],
  prompt: `You are a data analyst answering questions about data from a data lake.

  The question is: {{{question}}}
  The data is: {{{data}}}
  
  Answer the question using the provided data. If the question requires more specific data, you can use the getData tool.

  If you can not answer the question with the provided data, say that you cannot answer the question with the provided data.
`,
});

const llmPoweredQAFlow = ai.defineFlow(
  {
    name: 'llmPoweredQAFlow',
    inputSchema: LLMPoweredQAInputSchema,
    outputSchema: LLMPoweredQAOutputSchema,
  },
  async input => {
    const {output} = await prompt(input);
    return output!;
  }
);
